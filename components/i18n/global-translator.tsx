const PATTERNS: Array<[RegExp, string]> = [
  [/^الحملة\s+(\d+)%$/, "Campaign $1%"],
  [/^متبقي\s+(\d+)\s+يوم$/, "$1 days remaining"],
  [/^المتبقي:\s*(\d+)\s+يوم$/, "$1 days remaining"],
  [/^معلّق منذ\s+(\d+)\s+يوم/, "Pending for $1 days"],
  [/^(\d+(?:\.\d+)?)\s+ساعة$/, "$1 hours"],
];

function translateValue(value: string) {
  const trimmed = value.trim();
  if (!trimmed) return value;
  const exact = EXTRA_EXACT[trimmed] ?? EXACT[trimmed];
  if (exact) return value.replace(trimmed, exact);
  for (const [pattern, replacement] of PATTERNS) {
    if (pattern.test(trimmed)) return value.replace(trimmed, trimmed.replace(pattern, replacement));
  }

  let translated = trimmed;
  for (const [arabic, english] of [...EXTRA_FRAGMENTS, ...FRAGMENTS]) {
    if (translated.includes(arabic)) translated = translated.split(arabic).join(english);
  }
  return translated === trimmed ? value : value.replace(trimmed, translated);
}

const ORIGINAL_TEXT = new WeakMap<Text, string>();
const ORIGINAL_ATTRS = new WeakMap<HTMLElement, Map<string, string>>();

function rememberAttribute(element: HTMLElement, attribute: string, value: string) {
  const current = ORIGINAL_ATTRS.get(element) ?? new Map<string, string>();
  if (!current.has(attribute)) current.set(attribute, value);
  ORIGINAL_ATTRS.set(element, current);
}

function restoreTree(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes: Text[] = [];
  while (walker.nextNode()) nodes.push(walker.currentNode as Text);
  for (const node of nodes) {
    const original = ORIGINAL_TEXT.get(node);
    if (original !== undefined) node.nodeValue = original;
  }

  root.querySelectorAll<HTMLElement>("*").forEach((element) => {
    const attrs = ORIGINAL_ATTRS.get(element);
    if (attrs) attrs.forEach((value, key) => element.setAttribute(key, value));
    if (element.dataset.originalDir) {
      element.dir = element.dataset.originalDir;
      delete element.dataset.originalDir;
    }
  });
}

function translateTree(root: ParentNode) {
  const walker = document.createTreeWalker(root, NodeFilter.SHOW_TEXT);
  const nodes: Text[] = [];
  while (walker.nextNode()) nodes.push(walker.currentNode as Text);
  for (const node of nodes) {
    const parent = node.parentElement;
    if (!parent || parent.closest("script,style,textarea,[data-no-auto-translate]")) continue;
    const current = node.nodeValue ?? "";
    const translated = translateValue(current);
    if (translated !== current) {
      if (!ORIGINAL_TEXT.has(node)) ORIGINAL_TEXT.set(node, current);
      node.nodeValue = translated;
    }
  }

  root.querySelectorAll<HTMLElement>("[placeholder],[title],[aria-label],[alt]").forEach((element) => {
    for (const attribute of ["placeholder", "title", "aria-label", "alt"] as const) {
      const current = element.getAttribute(attribute);
      if (!current) continue;
      const translated = translateValue(current);
      if (translated !== current) {
        rememberAttribute(element, attribute, current);
        element.setAttribute(attribute, translated);
      }
    }
  });
}

export function GlobalTranslator({ locale }: { locale: AppLocale }) {
  useLayoutEffect(() => {
    const root = document.body;
    if (!root) return;

    if (locale === "ar") {
      restoreTree(root);
      document.documentElement.lang = "ar";
      document.documentElement.dir = "rtl";
      document.documentElement.dataset.locale = "ar";
      return;
    }

    const normalizeDirections = (scope: ParentNode) => {
      scope.querySelectorAll<HTMLElement>("[dir='rtl']").forEach((element) => {
        if (element.matches("input[type='tel'],input[type='email'],input[type='url'],[data-keep-dir]")) return;
        if (!element.dataset.originalDir) element.dataset.originalDir = "rtl";
        element.dir = "ltr";
      });
    };

    translateTree(root);
    normalizeDirections(root);

    const nativeAlert = window.alert.bind(window);
    const nativeConfirm = window.confirm.bind(window);
    window.alert = (message?: unknown) => nativeAlert(typeof message === "string" ? translateValue(message) : message);
    window.confirm = (message?: string) => nativeConfirm(translateValue(message ?? ""));

    const observer = new MutationObserver((mutations) => {
      for (const mutation of mutations) {
        if (mutation.type === "characterData" && mutation.target.parentNode) {
          translateTree(mutation.target.parentNode);
        }
        mutation.addedNodes.forEach((node) => {
          if (node.nodeType === Node.ELEMENT_NODE) {
            translateTree(node as Element);
            normalizeDirections(node as Element);
          }
          if (node.nodeType === Node.TEXT_NODE && node.parentNode) translateTree(node.parentNode);
        });
      }
    });
    observer.observe(root, { subtree: true, childList: true, characterData: true });
    return () => {
      observer.disconnect();
      window.alert = nativeAlert;
      window.confirm = nativeConfirm;
    };
  }, [locale]);

  return null;
}
